"""Ed25519 license-key signing — server side (verify-only mirror lives in
the client; the private key never leaves the server or your password manager).

Key format (identical on both sides):
    3L3-<b64url(payload_json)>.<b64url(signature)>

Payload is compact canonical JSON:
    {"exp": <epoch_seconds>, "iat": <epoch_seconds>, "kid": "<8 hex>", "v": 1}

  kid  = key id — used for activation counting and soft revocation
  v    = payload format version

SIGNING_PRIVATE_KEY env var: base64url-encoded raw 32-byte Ed25519 seed
(generated by mint_key.py --genkey) or a PEM private key. Clients embed the
public key only, so extracting the verifier from a shipped binary yields
nothing usable.
"""
from __future__ import annotations

import base64
import json
import os
import secrets

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey,
    Ed25519PublicKey,
)

PREFIX = "3L3-"
FORMAT_VERSION = 1


def _b64e(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).decode().rstrip("=")


def _b64d(s: str) -> bytes:
    pad = "=" * (-len(s) % 4)
    return base64.urlsafe_b64decode(s + pad)


def load_private_key() -> Ed25519PrivateKey:
    raw = os.getenv("SIGNING_PRIVATE_KEY", "").strip()
    if not raw:
        raise RuntimeError("SIGNING_PRIVATE_KEY not set")
    try:
        return Ed25519PrivateKey.from_private_bytes(_b64d(raw))
    except Exception:
        pass  # not a raw seed — try PEM
    key = serialization.load_pem_private_key(raw.encode(), password=None)
    if not isinstance(key, Ed25519PrivateKey):
        raise RuntimeError("SIGNING_PRIVATE_KEY is not an Ed25519 key")
    return key


def public_key_hex(priv: Ed25519PrivateKey) -> str:
    pub = priv.public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    return pub.hex()


def new_kid() -> str:
    return secrets.token_hex(4)


def sign_key(priv: Ed25519PrivateKey, iat: int, exp: int, kid: str) -> str:
    payload = json.dumps(
        {"v": FORMAT_VERSION, "kid": kid, "iat": int(iat), "exp": int(exp)},
        separators=(",", ":"), sort_keys=True).encode()
    sig = priv.sign(payload)
    return PREFIX + _b64e(payload) + "." + _b64e(sig)


def parse_and_verify(pub_hex: str, key_str: str) -> dict:
    """Verify signature + format. Returns the payload dict.
    Raises ValueError on anything malformed, bad signature or wrong version."""
    s = (key_str or "").strip()
    if not s.startswith(PREFIX):
        raise ValueError("not a 3lit3 license key")
    body = s[len(PREFIX):]
    if body.count(".") != 1:
        raise ValueError("malformed key")
    payload_b64, sig_b64 = body.split(".")
    try:
        payload = _b64d(payload_b64)
        sig = _b64d(sig_b64)
        pub = Ed25519PublicKey.from_public_bytes(bytes.fromhex(pub_hex))
        pub.verify(sig, payload)
    except ValueError:
        raise
    except Exception:
        raise ValueError("key signature is invalid")
    try:
        data = json.loads(payload.decode())
    except Exception:
        raise ValueError("key payload is malformed")
    if not isinstance(data, dict) or data.get("v") != FORMAT_VERSION:
        raise ValueError("unsupported key version")
    for field in ("kid", "iat", "exp"):
        if field not in data:
            raise ValueError("key payload is incomplete")
    return data
